-- 表空间（路径请按实际部署修改）
CREATE TABLESPACE CXMT_DATA
  DATAFILE '/oradata/CXMT_DATA.dbf' SIZE 1G AUTOEXTEND ON NEXT 100M MAXSIZE 10G;

CREATE TABLESPACE CXMT_IDX
  DATAFILE '/oradata/CXMT_IDX.dbf'  SIZE 500M AUTOEXTEND ON NEXT 50M MAXSIZE 5G;

CREATE TABLESPACE CXMT_AUDIT
  DATAFILE '/oradata/CXMT_AUDIT.dbf' SIZE 2G AUTOEXTEND ON NEXT 200M MAXSIZE UNLIMITED;

-- 平台用户
CREATE USER CXMT_PLATFORM IDENTIFIED BY "CXMTCode#2026"
  DEFAULT TABLESPACE CXMT_DATA
  QUOTA UNLIMITED ON CXMT_DATA
  QUOTA UNLIMITED ON CXMT_IDX
  QUOTA UNLIMITED ON CXMT_AUDIT;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE TRIGGER,
      CREATE INDEX, CREATE VIEW, CREATE PROCEDURE TO CXMT_PLATFORM;

-- 序列
CREATE SEQUENCE SEQ_AUDIT_LOG_ID START WITH 1 INCREMENT BY 1 CACHE 100;
