-- 审计日志（按季度分区）
CREATE TABLE CXMT_AUDIT_LOGS (
    LOG_ID           NUMBER(20)    NOT NULL,
    LOG_TIME         TIMESTAMP     NOT NULL,
    USER_ID          VARCHAR2(36)  NOT NULL,
    USER_NAME        VARCHAR2(64)  NOT NULL,
    USER_ROLE        NUMBER(1)     NOT NULL,
    ENVIRONMENT_TYPE VARCHAR2(8),
    OPERATION_TYPE   VARCHAR2(32)  NOT NULL,
    OPERATION_DESC   VARCHAR2(512) NOT NULL,
    TARGET_DATABASE  VARCHAR2(64),
    TARGET_TABLE     VARCHAR2(64),
    SQL_STATEMENT    CLOB,
    BEFORE_DATA      CLOB,
    AFTER_DATA       CLOB,
    CLIENT_IP        VARCHAR2(32),
    RESULT           VARCHAR2(16),
    HASH_VALUE       VARCHAR2(64)  NOT NULL,
    PREV_HASH        VARCHAR2(64),
    CONSTRAINT PK_CXMT_AUDIT_LOG PRIMARY KEY (LOG_ID) USING INDEX TABLESPACE CXMT_IDX
) TABLESPACE CXMT_AUDIT
PARTITION BY RANGE (LOG_TIME) (
    PARTITION P2026Q1 VALUES LESS THAN (TO_DATE('2026-04-01', 'YYYY-MM-DD')),
    PARTITION P2026Q2 VALUES LESS THAN (TO_DATE('2026-07-01', 'YYYY-MM-DD')),
    PARTITION P2026Q3 VALUES LESS THAN (TO_DATE('2026-10-01', 'YYYY-MM-DD')),
    PARTITION P2026Q4 VALUES LESS THAN (TO_DATE('2027-01-01', 'YYYY-MM-DD')),
    PARTITION P2027Q1 VALUES LESS THAN (TO_DATE('2027-04-01', 'YYYY-MM-DD')),
    PARTITION P2027Q2 VALUES LESS THAN (TO_DATE('2027-07-01', 'YYYY-MM-DD')),
    PARTITION P2027Q3 VALUES LESS THAN (TO_DATE('2027-10-01', 'YYYY-MM-DD')),
    PARTITION P2027Q4 VALUES LESS THAN (TO_DATE('2028-01-01', 'YYYY-MM-DD')),
    PARTITION PMAX    VALUES LESS THAN (MAXVALUE)
);
CREATE INDEX IDX_AUDIT_USER    ON CXMT_AUDIT_LOGS(USER_ID)    LOCAL TABLESPACE CXMT_IDX;
CREATE INDEX IDX_AUDIT_TIME    ON CXMT_AUDIT_LOGS(LOG_TIME)   LOCAL TABLESPACE CXMT_IDX;
CREATE INDEX IDX_AUDIT_OP_TYPE ON CXMT_AUDIT_LOGS(OPERATION_TYPE) LOCAL TABLESPACE CXMT_IDX;
CREATE INDEX IDX_AUDIT_ENV     ON CXMT_AUDIT_LOGS(ENVIRONMENT_TYPE) TABLESPACE CXMT_IDX;

